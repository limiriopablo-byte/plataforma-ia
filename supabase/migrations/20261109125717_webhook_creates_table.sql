create or replace function public.create_webhook(p uuid, p_name text, p_target text) returns uuid
language plpgsql security definer set search_path = '' as $$
declare aid uuid; r record;
begin
  select * into r from private._resolve(p, null, true);
  perform private._require(private._ident_ok(p_target), 'Nome de tabela inválido (use minúsculas, números e _)');
  if not exists (select 1 from public.project_tables where project_id = p and name = p_target) then
    -- cria a tabela vazia; as colunas surgem conforme os dados chegam
    execute format('create table %I.%I (id bigint generated by default as identity primary key, created_at timestamptz not null default now())', r.schema_name, p_target);
    insert into public.project_tables(project_id, name, label, columns) values (p, p_target, p_name, '[]');
  end if;
  insert into public.automations(project_id, name, kind, target_table, mode, webhook_token)
    values (p, p_name, 'webhook', p_target, 'append', encode(extensions.gen_random_bytes(24), 'hex')) returning id into aid;
  return aid;
end $$;
