-- Validação de identificadores SQL (nomes de tabela/coluna)
create or replace function public._ident_ok(s text) returns boolean
language sql immutable set search_path = '' as $$
  select s ~ '^[a-z_][a-z0-9_]{0,62}$' and s not in ('id','created_at')
$$;

create or replace function public._require(cond boolean, msg text) returns void
language plpgsql set search_path = '' as $$
begin if not coalesce(cond,false) then raise exception '%', msg using errcode = '42501'; end if; end $$;

-- Resolve projeto + tabela registrada, conferindo permissão
create or replace function public._resolve(p uuid, t text, need_dev boolean default false,
  out schema_name text, out cols jsonb)
language plpgsql stable security definer set search_path = '' as $$
declare ws uuid;
begin
  select pr.workspace_id, pr.schema_name into ws, schema_name from public.projects pr where pr.id = p;
  perform public._require(ws is not null, 'Projeto não encontrado');
  if need_dev then perform public._require(public.is_ws_dev(ws), 'Sem permissão (precisa ser dev)');
  else perform public._require(public.is_ws_member(ws), 'Sem acesso a este projeto'); end if;
  if t is not null then
    select pt.columns into cols from public.project_tables pt where pt.project_id = p and pt.name = t;
    perform public._require(cols is not null, 'Tabela não encontrada: ' || t);
  end if;
end $$;

-- ===== Workspaces e projetos =====
create or replace function public.create_workspace(p_name text) returns uuid
language plpgsql security definer set search_path = '' as $$
declare w uuid;
begin
  perform public._require(auth.uid() is not null, 'Faça login');
  insert into public.workspaces(name, created_by) values (p_name, auth.uid()) returning id into w;
  insert into public.workspace_members(workspace_id, user_id, role) values (w, auth.uid(), 'owner');
  return w;
end $$;

create or replace function public.create_project(p_workspace uuid, p_name text, p_description text default null) returns uuid
language plpgsql security definer set search_path = '' as $$
declare pid uuid := gen_random_uuid(); sch text := 'p_' || replace(left(pid::text, 13), '-', '');
begin
  perform public._require(public.is_ws_dev(p_workspace), 'Sem permissão (precisa ser dev)');
  insert into public.projects(id, workspace_id, name, description, schema_name) values (pid, p_workspace, p_name, p_description, sch);
  execute format('create schema %I', sch);
  execute format('revoke all on schema %I from public, anon, authenticated', sch);
  return pid;
end $$;

create or replace function public.delete_project(p uuid) returns void
language plpgsql security definer set search_path = '' as $$
declare r record;
begin
  select * into r from public._resolve(p, null, true);
  execute format('drop schema if exists %I cascade', r.schema_name);
  delete from public.projects where id = p;
end $$;

-- ===== Tabelas =====
-- p_columns: [{"name":"valor","type":"numeric","label":"Valor"}]
create or replace function public.create_table(p uuid, p_name text, p_label text, p_columns jsonb) returns void
language plpgsql security definer set search_path = '' as $$
declare r record; c jsonb; defs text := ''; typ text;
begin
  select * into r from public._resolve(p, null, true);
  perform public._require(public._ident_ok(p_name), 'Nome de tabela inválido (use minúsculas, números e _)');
  perform public._require(jsonb_typeof(p_columns) = 'array' and jsonb_array_length(p_columns) between 1 and 60, 'Informe de 1 a 60 colunas');
  for c in select * from jsonb_array_elements(p_columns) loop
    perform public._require(public._ident_ok(c->>'name'), 'Nome de coluna inválido: ' || coalesce(c->>'name','?'));
    typ := case c->>'type' when 'text' then 'text' when 'integer' then 'bigint' when 'numeric' then 'numeric'
      when 'boolean' then 'boolean' when 'date' then 'date' when 'timestamp' then 'timestamptz' end;
    perform public._require(typ is not null, 'Tipo inválido: ' || coalesce(c->>'type','?'));
    defs := defs || format(', %I %s', c->>'name', typ);
  end loop;
  execute format('create table %I.%I (id bigint generated by default as identity primary key, created_at timestamptz not null default now()%s)', r.schema_name, p_name, defs);
  insert into public.project_tables(project_id, name, label, columns) values (p, p_name, coalesce(nullif(p_label,''), p_name), p_columns);
end $$;

create or replace function public.drop_table(p uuid, p_name text) returns void
language plpgsql security definer set search_path = '' as $$
declare r record;
begin
  select * into r from public._resolve(p, p_name, true);
  execute format('drop table %I.%I', r.schema_name, p_name);
  delete from public.project_tables where project_id = p and name = p_name;
end $$;

-- ===== CRUD =====
create or replace function public._col_list(cols jsonb, data jsonb) returns text
language sql immutable set search_path = '' as $$
  select string_agg(format('%I', c->>'name'), ',')
  from jsonb_array_elements(cols) c where data ? (c->>'name')
$$;

create or replace function public.list_rows(p uuid, p_table text, p_limit int default 100, p_offset int default 0,
  p_order text default 'id', p_desc boolean default true) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare r record; rows jsonb; total bigint;
begin
  select * into r from public._resolve(p, p_table);
  if p_order not in ('id','created_at') and not exists(select 1 from jsonb_array_elements(r.cols) c where c->>'name' = p_order) then p_order := 'id'; end if;
  execute format('select count(*) from %I.%I', r.schema_name, p_table) into total;
  execute format('select coalesce(jsonb_agg(to_jsonb(t)), ''[]'') from (select * from %I.%I order by %I %s limit %s offset %s) t',
    r.schema_name, p_table, p_order, case when p_desc then 'desc' else 'asc' end, least(greatest(p_limit,1),1000), greatest(p_offset,0)) into rows;
  return jsonb_build_object('rows', rows, 'total', total, 'columns', r.cols);
end $$;

create or replace function public.insert_rows(p uuid, p_table text, p_rows jsonb) returns int
language plpgsql security definer set search_path = '' as $$
declare r record; d jsonb; cl text; n int := 0;
begin
  select * into r from public._resolve(p, p_table);
  perform public._require(jsonb_typeof(p_rows) = 'array' and jsonb_array_length(p_rows) <= 5000, 'Envie até 5000 linhas por vez');
  for d in select * from jsonb_array_elements(p_rows) loop
    cl := public._col_list(r.cols, d);
    if cl is null then continue; end if;
    execute format('insert into %I.%I (%s) select %s from jsonb_populate_record(null::%I.%I, $1)', r.schema_name, p_table, cl, cl, r.schema_name, p_table) using d;
    n := n + 1;
  end loop;
  return n;
end $$;

create or replace function public.update_row(p uuid, p_table text, p_id bigint, p_data jsonb) returns void
language plpgsql security definer set search_path = '' as $$
declare r record; cl text;
begin
  select * into r from public._resolve(p, p_table);
  cl := public._col_list(r.cols, p_data);
  perform public._require(cl is not null, 'Nada para atualizar');
  execute format('update %I.%I set (%s) = (select %s from jsonb_populate_record(null::%I.%I, $1)) where id = $2',
    r.schema_name, p_table, cl, cl, r.schema_name, p_table) using p_data, p_id;
end $$;

create or replace function public.delete_rows(p uuid, p_table text, p_ids bigint[]) returns void
language plpgsql security definer set search_path = '' as $$
declare r record;
begin
  select * into r from public._resolve(p, p_table);
  execute format('delete from %I.%I where id = any($1)', r.schema_name, p_table) using p_ids;
end $$;

-- ===== BI: agregação segura (sem SQL livre) =====
create or replace function public.aggregate(p uuid, p_table text, p_agg text default 'count', p_metric text default null,
  p_group text default null, p_trunc text default null, p_limit int default 50) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare r record; expr text; grp text; res jsonb;
  valid text[];
begin
  select * into r from public._resolve(p, p_table);
  select array_agg(c->>'name') || array['id','created_at'] into valid from jsonb_array_elements(r.cols) c;
  perform public._require(p_agg in ('count','sum','avg','min','max'), 'Agregação inválida');
  if p_agg = 'count' then expr := 'count(*)';
  else perform public._require(p_metric = any(valid), 'Coluna de métrica inválida'); expr := format('%s(%I)', p_agg, p_metric); end if;
  if p_group is null or p_group = '' then
    execute format('select jsonb_build_array(jsonb_build_object(''label'', ''Total'', ''value'', %s)) from %I.%I', expr, r.schema_name, p_table) into res;
    return res;
  end if;
  perform public._require(p_group = any(valid), 'Coluna de agrupamento inválida');
  if p_trunc in ('day','week','month','year') then grp := format('date_trunc(%L, %I)::date', p_trunc, p_group);
  else grp := format('%I', p_group); end if;
  execute format('select coalesce(jsonb_agg(jsonb_build_object(''label'', g, ''value'', v) order by %s), ''[]'') from (select %s as g, %s as v from %I.%I group by 1 order by %s limit %s) s',
    case when p_trunc is not null then 'g' else 'v desc' end, grp, expr, r.schema_name, p_table,
    case when p_trunc is not null then '1' else '2 desc' end, least(greatest(p_limit,1),500)) into res;
  return res;
end $$;

-- Permissões de execução: só usuários logados
do $$ declare f text; begin
  for f in select p.oid::regprocedure::text from pg_proc p join pg_namespace n on n.oid = p.pronamespace
           where n.nspname = 'public' and p.proname in ('create_workspace','create_project','delete_project','create_table','drop_table',
             'list_rows','insert_rows','update_row','delete_rows','aggregate','ws_role','is_ws_member','is_ws_dev','project_ws',
             '_resolve','_require','_ident_ok','_col_list') loop
    execute format('revoke execute on function %s from public, anon', f);
    execute format('grant execute on function %s to authenticated', f);
  end loop;
end $$;
